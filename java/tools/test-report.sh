#!/usr/bin/env bash
# Builds and tests in the pinned Maven image, runs tools/conformance.py on the jar, and writes java/reports/.
set -euo pipefail

IMAGE="maven:3.9.11-eclipse-temurin-17@sha256:e4a7ace3dc0d645ed97f8d9ad0b0d3f0b14fa8d150138f27f116d7105a639b82"
JAVA_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO_DIR="$(cd "${JAVA_DIR}/.." && pwd)"
M2_DIR="${MONTY_LAB_M2:-${HOME}/.m2}"
REPORTS="${JAVA_DIR}/reports"

mkdir -p "${M2_DIR}" "${REPORTS}/tests"
set +e
docker run --rm -u "$(id -u):$(id -g)" \
  -v "${REPO_DIR}:/work" -w /work/java \
  -v "${M2_DIR}:/var/maven/.m2" -e MAVEN_CONFIG=/var/maven/.m2 \
  "${IMAGE}" mvn -B -ntp -Duser.home=/var/maven clean verify
maven_status=$?
set -e

rm -f "${REPORTS}"/tests/TEST-*.xml
cp "${JAVA_DIR}"/target/surefire-reports/TEST-*.xml "${REPORTS}/tests/"

total=0; failures=0; errors=0; skipped=0
for file in "${REPORTS}"/tests/TEST-*.xml; do
  header="$(grep -m1 -o '<testsuite [^>]*>' "${file}")"
  attribute() { grep -o " $1=\"[0-9]*\"" <<<"${header}" | grep -o '[0-9]*'; }
  total=$((total + $(attribute tests)))
  failures=$((failures + $(attribute failures)))
  errors=$((errors + $(attribute errors)))
  skipped=$((skipped + $(attribute skipped)))
done
passed=$((total - failures - errors - skipped))

set +e
(cd "${REPO_DIR}" && python3 -I tools/conformance.py --cli "java -jar java/target/monty-lab.jar" \
  --report java/reports/conformance.json) > "${REPORTS}/conformance.txt" 2>&1
conformance_status=$?
set -e

{
  echo "# Test Report"
  echo
  echo "- Generated (UTC): $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "- Build image: \`${IMAGE}\`"
  echo "- Build command: \`mvn -B -ntp clean verify\` (exit code ${maven_status})"
  echo "- Conformance runtime: $(java -version 2>&1 | head -n1)"
  echo "- Conformance command: \`python3 -I tools/conformance.py --cli \"java -jar java/target/monty-lab.jar\"\` (exit code ${conformance_status})"
  echo "- Python for conformance: $(python3 --version 2>&1)"
  echo "- Generated by: \`java/tools/test-report.sh\`"
  echo
  echo "## JUnit"
  echo
  echo "| Total | Passed | Failed | Errors | Skipped |"
  echo "| ---: | ---: | ---: | ---: | ---: |"
  echo "| ${total} | ${passed} | ${failures} | ${errors} | ${skipped} |"
  echo
  echo "Per-test results are in the \`TEST-*.xml\` files in this directory."
  echo
  echo "## Conformance"
  echo
  echo '```text'
  cat "${REPORTS}/conformance.txt"
  echo '```'
  echo
  echo "The machine-readable result is \`../conformance.json\`."
} > "${REPORTS}/tests/test-report.md"

rm -f "${REPORTS}/conformance.txt"
cat "${REPORTS}/tests/test-report.md"
if [[ ${maven_status} -ne 0 || ${conformance_status} -ne 0 ]]; then
  exit 1
fi
